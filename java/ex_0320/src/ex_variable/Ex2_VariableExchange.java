package ex_variable;

public class Ex2_VariableExchange {
	public static void main(String[] args) {
		int x = 3;
		int y = 5;
		//변수 x에 들어있는 값과 변수 y에 들어있는 값을
		//교환해주세요
		//필요하다면 변수를 또 만들어도 된다.
		
		int temp;
		temp = x;
		x = y;
		y = temp;
		
		System.out.println("x : " + x);
		System.out.println("y : " + y);
		
		int 나이 = 29;
		System.out.println("나이 : " + 나이);
		
		
		
		
		
		
		
		
	}
}
